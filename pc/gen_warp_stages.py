#!/usr/bin/env python3
"""Generates pc/shim/warp_stages.inc, the debug-warp stage table.

Run from the repo root:  .venv/bin/python -I pc/gen_warp_stages.py

Inputs (the decomp C only, no disc data):
  * src/field/field_mode/data/fieldstg.c -- the European tables
    FIELDSTG_extraStages (used only when GAME.progress == FIELD_PROGRESS_EXTRA,
    see FIELDSTG_pickStage in field_mode/state.c) and FIELDSTG_stages (every
    other progress). Rows are {mode, file, WSTAGnnn_startStage}.
  * src/field/stages/**/wstagNNN.c -- each stage's setupStage start
    (FIELDSTG_state.start / startDir).

Output rows: { stage, mode, {startX, startY}, dir, progress }. progress is -1
when the default table holds the stage, FIELD_PROGRESS_EXTRA (0x2D) when only
the extra table does. Stages without a literal start or without a row in any
table are listed in a comment.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FIELDSTG = ROOT / "src/field/field_mode/data/fieldstg.c"
STAGES = ROOT / "src/field/stages"
OUT = ROOT / "pc/shim/warp_stages.inc"
EXTRA_PROGRESS = 0x2D

ROW = re.compile(r"\{\s*(\d+)\s*,\s*\d+\s*,\s*WSTAG(\d+)_startStage\s*\}")
START = re.compile(
    r"FIELDSTG_state\.start\s*=\s*\(Vec2\)\{\s*(0x[0-9A-Fa-f]+|\d+)\s*,\s*(0x[0-9A-Fa-f]+|\d+)\s*\}\s*;")
DIR = re.compile(r"FIELDSTG_state\.startDir\s*=\s*(0x[0-9A-Fa-f]+|\d+)\s*;")


def eu_table(text, name):
    """Rows of the EU definition of table `name` (the last definition, after
    the #elif VERSION_EU of the data block)."""
    eu = text[text.index("#elif VERSION_EU", text.index("FIELDSTG_stages[]")):]
    start = eu.index("StageEntry %s[]" % name)
    end = eu.index("};", start)
    return [(int(m.group(1)), int(m.group(2))) for m in ROW.finditer(eu[start:end])]


def main():
    text = FIELDSTG.read_text()
    extra = eu_table(text, "FIELDSTG_extraStages")
    main_rows = eu_table(text, "FIELDSTG_stages")

    # first row wins inside a table (FIELDSTG_pickStage stops at the first mode
    # match), so a stage's mode is the first mode that names it
    default_mode, extra_mode = {}, {}
    for mode, stage in main_rows:
        default_mode.setdefault(stage, mode)
    for mode, stage in extra:
        extra_mode.setdefault(stage, mode)

    starts, bad = {}, {}
    for path in sorted(STAGES.rglob("wstag*.c")):
        m = re.fullmatch(r"wstag(\d+)\.c", path.name)
        if not m:
            continue
        stage = int(m.group(1))
        src = path.read_text()
        s, d = START.search(src), DIR.search(src)
        if s and d:
            starts[stage] = (int(s.group(1), 0), int(s.group(2), 0), int(d.group(1), 0))
        else:
            bad[stage] = "setupStage start is not a plain literal"

    rows, nodes = [], []
    for stage in sorted(set(starts) | set(bad)):
        if stage in default_mode:
            mode, progress = default_mode[stage], -1
        elif stage in extra_mode:
            mode, progress = extra_mode[stage], EXTRA_PROGRESS
        else:
            nodes.append("%d (no row in any FIELDSTG table)" % stage)
            continue
        if stage in bad:
            nodes.append("%d (%s)" % (stage, bad[stage]))
            continue
        x, y, d = starts[stage]
        rows.append("    { %d, 0x%X, { 0x%X, 0x%X }, %d, %d }," % (stage, mode, x, y, d, progress))

    out = ["/* GENERATED by pc/gen_warp_stages.py -- do not edit by hand.",
           "   { stage, mode, start, dir, progress }: progress is -1 when the default",
           "   FIELDSTG_stages holds the stage, 0x2D (FIELD_PROGRESS_EXTRA) when only the",
           "   EU extra table FIELDSTG_extraStages does. %d stages." % len(rows)]
    if nodes:
        out.append("   Without an entry (not warpable): " + ", ".join(nodes) + ". */")
    else:
        out.append("   Every stage has an entry. */")
    out.extend(rows)
    OUT.write_text("\n".join(out) + "\n")
    print("wrote %s: %d rows, %d without entry" % (OUT.relative_to(ROOT), len(rows), len(nodes)))


if __name__ == "__main__":
    sys.exit(main())
