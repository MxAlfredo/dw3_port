#!/usr/bin/env python3
"""State-scope sections of the port's overlays (pc/ovl_sections.ld).

usage:
  check_scopes.py gen <out.ld> <out.c> <stage object>...
      writes the linker fragment and the C table of the field stages (one scope each);
  check_scopes.py pe <out.ld> <build dir> <ovl_sections.ld> [<more .ld>...]
      Windows (PE) only: rewrites the ELF statements into ONE output section (see below);
  check_scopes.py check <boot binary> <build dir> <ovl_sections.ld> [<more .ld>...]
      validates the linked binary against every `ovl_<name>_data` statement of the scripts.

The scripts are always the ELF ones (pc/ovl_sections.ld and the generated stage twin): they are the
single source of truth for which objects belong to which scope. For a PE target (CROSS_PREFIX set,
e.g. x86_64-w64-mingw32-) `pe` derives the linker script from them: the Windows loader copes badly
with hundreds of output sections (312 scopes here), so every range becomes a start/end symbol pair
inside a single `.ovldat` section, and the section list also accepts COFF's `.data$x` / `.bss$x`.
Objects are matched with the script's `*build/` prefix rewritten to <build dir>'s name.

check, for each statement (its object patterns, its section list, its range symbols):
  1. the objects under <build dir> its patterns claim are found; no object is claimed by two
     statements, and none has a read-only data section the statement would have to move;
  2. every writable (ALLOC, not READONLY, not CODE) section of those objects matches the
     statement's section list, so the linker really moved it into the range;
  3. every writable symbol (nm types D d B b G g S s) those objects define lies inside
     [__ovl_<name>_data_start, __ovl_<name>_data_end) of the linked binary;
  4. CARDGAME_markedCounts (defined by the host, not by an overlay object) is inside cardgame's.
Exit 0 when all held, 1 otherwise. Prints one line per scope: symbols checked and bytes.
"""
import fnmatch
import glob
import os
import re
import subprocess
import sys

WRITABLE = set("DdBbGgSs")
EXTRA_SYMBOLS = {"cardgame": ["CARDGAME_markedCounts"]}
SECTIONS = ".data .data.* .sdata .sdata.* .bss .bss.* .sbss .sbss.* COMMON"
# the stage's startStage is the key the host looks the scope up by (boot.c)


PREFIX = os.environ.get("CROSS_PREFIX", "")
PE_SECTIONS = ".data$* .sdata$* .bss$* .sbss$*"


def run(*cmd):
    cmd = (PREFIX + cmd[0],) + cmd[1:] if cmd[0] in ("nm", "objdump") else cmd
    return subprocess.run(cmd, check=True, capture_output=True, text=True).stdout


def stage_groups(objs):
    """{ 'wstag924': [objects] } from .../wstagNNN.o and .../wstagNNN_head.o."""
    groups = {}
    for obj in objs:
        m = re.search(r"/(wstag\d+)(_head)?\.o$", obj)
        if m:
            groups.setdefault(m.group(1), []).append(obj)
    return groups


def gen(out_ld, out_c, objs):
    groups = stage_groups(objs)
    ld = ["/* Generated by pc/check_scopes.py gen: one range per field stage (WSTAG###). */", "SECTIONS", "{"]
    c = ['/* Generated by pc/check_scopes.py gen. */', '#include "shim/state_scope.h"', ""]
    rows = []
    for name in sorted(groups):
        ld.append("    ovl_%s_data : ALIGN(64)\n    {\n        __ovl_%s_data_start = .;" % (name, name))
        for obj in sorted(groups[name]):
            ld.append("        */%s(%s)" % (obj.split("/stages/", 1)[1] if "/stages/" in obj else obj, SECTIONS))
        ld.append("        . = ALIGN(64);\n        __ovl_%s_data_end = .;\n    }" % name)
        c.append("extern char __ovl_%s_data_start[], __ovl_%s_data_end[];" % (name, name))
        has_start = any("T WSTAG" in l and l.endswith("_startStage") and name.upper() in l
                        for o in groups[name] if os.path.exists(o) for l in run("nm", o).splitlines())
        if has_start:
            c.append("extern void %s_startStage(void);" % name.upper())
        rows.append((name, has_start))
    ld += ["}", "INSERT AFTER .data;", ""]
    c += ["", "const StateScopeRange PC_STAGE_SCOPE_RANGES[] = {"]
    for name, has_start in rows:
        c.append('    {"%s", %s, __ovl_%s_data_start, __ovl_%s_data_end},' % (
            name, ("(const void *)%s_startStage" % name.upper()) if has_start else "0", name, name))
    c += ["    {0, 0, 0, 0}", "};", ""]
    open(out_ld, "w").write("\n".join(ld))
    open(out_c, "w").write("\n".join(c))
    return 0


def parse_lines(path, build_dir="build"):
    """[(name, [(object pattern, [section patterns])])] from the `ovl_<name>_data` statements."""
    text = re.sub(r"(?<![\w*])/\*.*?\*/", "", open(path).read(), flags=re.S)
    statements = []
    for m in re.finditer(r"ovl_(\w+?)_data\s*:[^{]*\{(.*?)\n\s*\}", text, flags=re.S):
        lines = []
        for line in m.group(2).splitlines():
            lm = re.match(r"(\S+)\((.*)\)$", line.strip())
            if lm:
                obj = lm.group(1)
                if obj.startswith("*build/"):
                    obj = "*%s/%s" % (os.path.basename(os.path.normpath(build_dir)), obj[len("*build/"):])
                lines.append((obj, lm.group(2).split()))
        statements.append((m.group(1), lines))
    return statements


def parse_script(path, build_dir="build", pe=False):
    """[(name, [object patterns], [section patterns])] from the `ovl_<name>_data` statements."""
    statements = []
    for name, lines in parse_lines(path, build_dir):
        objs = [obj for obj, _ in lines]
        secs = [sec for _, ss in lines for sec in ss] + (PE_SECTIONS.split() if pe else [])
        statements.append((name, objs, secs))
    return statements


def pe_script(out_ld, build_dir, scripts):
    lines = ["/* Generated by pc/check_scopes.py pe: every scope range inside one PE section. */",
             "SECTIONS", "{", "    .ovldat BLOCK(__section_alignment__) :", "    {"]
    for script in scripts:
        for name, stmt in parse_lines(script, build_dir):
            lines.append("        . = ALIGN(64);\n        __ovl_%s_data_start = .;" % name)
            for obj, secs in stmt:
                # a file-less line (`*(.bss.ovl_x)`) keeps its own list: widening it would swallow
                # every writable input section of the link
                extra = PE_SECTIONS.split() if obj.endswith(".o") else []
                lines.append("        %s(%s)" % (obj, " ".join(dict.fromkeys(secs + extra))))
            lines.append("        . = ALIGN(64);\n        __ovl_%s_data_end = .;" % name)
    lines += ["    }", "}", "INSERT AFTER .data;", ""]
    open(out_ld, "w").write("\n".join(lines))
    return 0


def writable_sections(obj):
    """Names of the sections the linker treats as writable data: ALLOC, not READONLY, not CODE."""
    lines = run("objdump", "-h", obj).splitlines()
    found = []
    for i, line in enumerate(lines):
        m = re.match(r"\s*\d+\s+(\S+)\s+([0-9a-f]+)\s", line)
        if m and i + 1 < len(lines):
            flags = lines[i + 1]
            if "ALLOC" in flags and "READONLY" not in flags and "CODE" not in flags and int(m.group(2), 16) > 0:
                found.append(m.group(1))
    return found


def check(binary, build_dir, scripts):
    pe = open(binary, "rb").read(2) == b"MZ"
    linked = {}
    for line in run("nm", binary).splitlines():
        parts = line.split()
        if len(parts) == 3:
            linked.setdefault(parts[2], []).append(int(parts[0], 16))
    all_objs = sorted(glob.glob("%s/**/*.o" % build_dir, recursive=True))
    failures = 0
    claimed = {}
    for script in scripts:
        for name, obj_patterns, secs in parse_script(script, build_dir, pe):
            start = linked.get("__ovl_%s_data_start" % name)
            end = linked.get("__ovl_%s_data_end" % name)
            if not start or not end:
                print("check_scopes: no range symbols for %s" % name)
                failures += 1
                continue
            lo, hi = start[0], end[0]
            checked = 0
            for obj in all_objs:
                if not any(fnmatch.fnmatchcase(obj, p) for p in obj_patterns if p.endswith(".o")):
                    continue
                if obj in claimed:
                    print("check_scopes: %s is claimed by both %s and %s" % (obj, claimed[obj], name))
                    failures += 1
                claimed[obj] = name
                for sec in writable_sections(obj):
                    if sec.startswith(".data.rel.ro") or not any(fnmatch.fnmatchcase(sec, s) for s in secs):
                        print("check_scopes: %s has a section %s the %s statement does not move" % (obj, sec, name))
                        failures += 1
                for line in run("nm", obj).splitlines():
                    parts = line.split()
                    if len(parts) != 3 or parts[1] not in WRITABLE:
                        continue
                    addrs = linked.get(parts[2], [])
                    if parts[2].startswith(".") or not addrs:
                        continue  # a local the linker renamed or dropped (unreferenced)
                    checked += 1
                    if not any(lo <= a < hi for a in addrs):
                        print("check_scopes: %s (%s) is outside %s [%#x, %#x): %s" % (
                            parts[2], obj, name, lo, hi, ", ".join(hex(a) for a in addrs)))
                        failures += 1
            for sym in EXTRA_SYMBOLS.get(name, []):
                checked += 1
                if not any(lo <= a < hi for a in linked.get(sym, [])):
                    print("check_scopes: %s is outside %s [%#x, %#x)" % (sym, name, lo, hi))
                    failures += 1
            print("check_scopes: %-9s %#x..%#x %7d bytes, %4d writable symbols" % (name, lo, hi, hi - lo, checked))
    return 1 if failures else 0


if len(sys.argv) >= 5 and sys.argv[1] == "gen":
    sys.exit(gen(sys.argv[2], sys.argv[3], sys.argv[4:]))
if len(sys.argv) >= 5 and sys.argv[1] == "pe":
    sys.exit(pe_script(sys.argv[2], sys.argv[3], sys.argv[4:]))
if len(sys.argv) >= 5 and sys.argv[1] == "check":
    sys.exit(check(sys.argv[2], sys.argv[3], sys.argv[4:]))
sys.exit(__doc__)
